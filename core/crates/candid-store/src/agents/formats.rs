use super::*;
use crate::ids::sha256_hex;
use std::io::{BufRead, BufReader, Read, Seek, SeekFrom};

fn s<'a>(v: &'a Value, k: &str) -> Option<&'a str> {
    v.get(k).and_then(Value::as_str)
}
fn n(v: &Value, k: &str) -> i64 {
    v[k].as_i64().unwrap_or(0)
}
fn text_blocks(v: &Value, types: &[&str]) -> String {
    if let Some(s) = v.as_str() {
        return s.into();
    }
    v.as_array()
        .map(|a| {
            a.iter()
                .filter(|b| s(b, "type").is_some_and(|t| types.contains(&t)))
                .filter_map(|b| s(b, "text").or_else(|| s(b, "thinking")))
                .collect::<Vec<_>>()
                .join("\n\n")
        })
        .unwrap_or_default()
}
fn timestamp(v: &Value) -> Result<(i64, Option<i64>)> {
    if let Some(t) = s(v, "timestamp") {
        let dt =
            chrono::DateTime::parse_from_rfc3339(t).map_err(|_| failure("invalid_envelope"))?;
        return Ok((
            dt.timestamp_millis(),
            Some((dt.offset().local_minus_utc() / 60) as i64),
        ));
    }
    if let Some(t) = v["message"]["timestamp"].as_i64() {
        return Ok((t, None));
    }
    Err(failure("invalid_envelope"))
}
fn foreign(v: &Value) -> bool {
    [
        "isMeta",
        "isCompactSummary",
        "isSummary",
        "isInjected",
        "isReplay",
        "isImported",
        "isSidechain",
    ]
    .iter()
    .any(|k| v[*k].as_bool() == Some(true))
        || [
            "sourceSessionId",
            "source_session_id",
            "originSessionId",
            "fromSessionId",
        ]
        .iter()
        .any(|k| !v[*k].is_null())
        || ["source", "origin", "provenance"].iter().any(|k| {
            let x = &v[*k];
            x.as_str()
                .is_some_and(|t| !["user", "human", "input", "interactive"].contains(&t))
                // Newer Claude Code marks typed prompts `origin: {kind: "human"}`; any other kind (task
                // notifications, peers) is not the person's own words.
                || (x.is_object() && !s(x, "kind").is_some_and(|t| ["human", "user"].contains(&t)))
        })
}
fn human_text(t: &str) -> Option<String> {
    let head = t.trim_start();
    let injected = [
        "<environment_context",
        "<user_instructions",
        "# AGENTS.md instructions",
        "<permissions",
        "<INSTRUCTIONS",
        "<turn_aborted",
        "<collaboration_mode",
        "<system-reminder",
        "<local-command-caveat",
        "<local-command-stdout",
        "<task-notification",
        "<teammate-message",
        "<codex_delegation",
        "<context_summary",
        "<summary>",
        "[Request interrupted by user",
        "This session is being continued from a previous conversation",
        "You are continuing a conversation that was compacted",
        "<skill>",
        "<developer_instructions",
        "<skills_instructions",
        "<app-context",
        "<context_summary>",
        "The following is a summary of the conversation",
        "Message Type: MESSAGE",
    ];
    if injected.iter().any(|p| head.starts_with(p))
        || head.contains("<source_thread_id>")
        || head.contains("<codex_delegation>")
    {
        return None;
    }
    if let Some(a) = head.find("<command-name>") {
        let cmd = &head[a + 14..];
        return cmd
            .split("</command-name>")
            .next()
            .map(str::trim)
            .filter(|s| s.starts_with('/'))
            .map(str::to_string);
    }
    // Expanded slash-command/skill bodies are not user speech.
    if head.starts_with("<command-message>") || head.starts_with("<skill_content") {
        return None;
    }
    (!head.is_empty()).then(|| t.to_owned())
}
fn user_text(content: &Value) -> Option<String> {
    if let Some(t) = content.as_str() {
        return human_text(t);
    }
    let a = content.as_array()?;
    // A tool result envelope may have adjacent explanatory text generated by the runner.
    if a.iter()
        .any(|b| ["tool_result", "toolResult"].contains(&s(b, "type").unwrap_or("")))
    {
        return None;
    }
    let text = a
        .iter()
        .filter(|b| ["text", "input_text"].contains(&s(b, "type").unwrap_or("")))
        .filter_map(|b| s(b, "text"))
        .filter_map(human_text)
        .collect::<Vec<_>>()
        .join("\n\n");
    (!text.is_empty()).then_some(text)
}
fn usage(v: &Value, pi: bool) -> Usage {
    Usage {
        input: if pi {
            v["input"].as_i64().unwrap_or(n(v, "input_tokens"))
        } else {
            n(v, "input_tokens")
        },
        output: if pi {
            v["output"].as_i64().unwrap_or(n(v, "output_tokens"))
        } else {
            n(v, "output_tokens")
        },
        cache_read: if pi {v["cacheRead"].as_i64().unwrap_or(n(v,"cache_read"))}else{n(v,"cache_read_input_tokens")},
        cache_write: if pi {v["cacheWrite"].as_i64().unwrap_or(n(v,"cache_write"))}else{n(v,"cache_creation_input_tokens")},
        reasoning: v["reasoning_output_tokens"]
            .as_i64()
            .unwrap_or_else(|| n(&v["output_tokens_details"], "thinking_tokens")),
    }
}
fn path_for(tool: &str, args: &Value) -> Option<String> {
    if ![
        "Edit",
        "Write",
        "MultiEdit",
        "edit",
        "write",
        "apply_patch",
        "functions.apply_patch",
        "functions__apply_patch",
    ]
    .contains(&tool)
    {
        return None;
    }
    s(args, "file_path")
        .or_else(|| s(args, "path"))
        .map(String::from)
}
fn recognize(agent: &str, lines: &[Value]) -> Result<()> {
    let Some(first) = lines.first() else {
        return Ok(());
    };
    let ok = match agent {
        "codex" => s(first, "type") == Some("session_meta") && first["payload"].is_object(),
        "claude_code" => lines
            .iter()
            .any(|v| s(v, "sessionId").is_some() && s(v, "type").is_some()),
        "pi" => s(first, "type") == Some("session") && n(first, "version") == 3,
        _ => false,
    };
    if ok {
        Ok(())
    } else {
        Err(failure("unknown_format"))
    }
}
pub(super) fn parse(agent: &str, v: &Value, st: &mut Session) -> Result<Vec<Entry>> {
    let typ = s(v, "type").ok_or_else(|| failure("invalid_envelope"))?;
    let p = if agent == "codex" { &v["payload"] } else { v };
    if (agent == "codex" && typ == "session_meta") || (agent == "pi" && typ == "session") {
        let id = s(p, "id").ok_or_else(|| failure("invalid_envelope"))?;
        if !st.key.is_empty() && st.key != id {
            return Err(failure("session_identity_changed"));
        }
        st.key = id.into();
        st.project = s(p, "cwd").map(String::from);
        if agent == "codex" { st.agent_thread = s(p, "thread_source").is_some_and(|t| t != "user"); }
        return Ok(vec![]);
    }
    if agent == "claude_code" {
        if let Some(id) = s(v, "sessionId") {
            if !st.key.is_empty() && st.key != id {
                return Err(failure("session_identity_changed"));
            }
            st.key = id.into();
        }
        if let Some(cwd) = s(v, "cwd") {
            st.project = Some(cwd.into());
        }
        if typ == "custom-title" {
            st.title = s(v, "customTitle").map(String::from);
            return Ok(vec![]);
        }
    }
    if agent == "codex" && typ == "turn_context" {
        st.model = s(p, "model").map(String::from);
        return Ok(vec![]);
    }
    let relevant = match agent {
        "codex" => ["response_item", "event_msg"].contains(&typ),
        "claude_code" => ["user", "assistant"].contains(&typ),
        _ => typ == "message",
    };
    if !relevant {
        return Ok(vec![]);
    }
    let (ts, offset) = timestamp(v)?;
    let id = if let Some(id) = s(p, "id").or_else(|| s(v, "uuid")) {
        id.to_owned()
    } else {
        let hash = sha256_hex(crate::json::canonical(v));
        let count = st.fallback_counts.entry(hash.clone()).or_default();
        *count += 1;
        format!("h{}-{}", &hash[..32], count)
    };
    let base = Entry {
        id,
        source_hash: sha256_hex(crate::json::canonical(v)),
        ts,
        offset,
        ..Default::default()
    };
    let make = |kind: &str, role: &str, text: Option<String>, tool: Option<String>| Entry {
        kind: kind.into(),
        role: role.into(),
        text,
        tool,
        ..base.clone()
    };
    if agent == "codex" && typ == "event_msg" {
        let t = s(p, "type").unwrap_or("");
        if [
            "task_complete",
            "task_completed",
            "turn_complete",
            "turn_completed",
            "turn_aborted",
            "task_aborted",
        ]
        .contains(&t)
        {
            return Ok(vec![Entry {
                kind: "status".into(),
                status: Some(
                    if t.ends_with("aborted") {
                        "interrupted"
                    } else {
                        "done"
                    }
                    .into(),
                ),
                ..base
            }]);
        }
        if t == "token_count" {
            let u = &p["info"]["last_token_usage"];
            if u.is_null() {
                return Ok(vec![]);
            }
            let mut u = usage(u, false);
            u.cache_read = n(&p["info"]["last_token_usage"], "cached_input_tokens");
            return Ok(vec![Entry {
                kind: "usage".into(),
                usage: Some(u),
                ..base
            }]);
        }
        if st.agent_thread {
            return Ok(vec![]);
        }
        if t == "user_message" && !foreign(v) && !foreign(p) {
            if let Some(t) = s(p, "message").and_then(human_text) {
                return Ok(vec![make("humanMessage", "user", Some(t), None)]);
            }
        }
        // Newer Codex clients record the send as a completed `UserMessage` item carrying the client's id.
        let item = &p["item"];
        if t == "item_completed" && s(item, "type") == Some("UserMessage") && s(item, "client_id").is_some()
            && !foreign(v) && !foreign(p) && !foreign(item)
        {
            if let Some(text) = human_text(&text_blocks(&item["content"], &["text"])) {
                let mut e = make("humanMessage", "user", Some(text), None);
                if let Some(id) = s(item, "id") { e.id = id.into(); }
                return Ok(vec![e]);
            }
        }
        return Ok(vec![]);
    }
    if agent == "codex" {
        match s(p, "type").unwrap_or("") {
            "message" => {}
            "function_call" | "custom_tool_call" => {
                let name = s(p, "name").ok_or_else(|| failure("unsupported_shape"))?;
                let args = s(p, "arguments")
                    .and_then(|a| serde_json::from_str::<Value>(a).ok())
                    .unwrap_or_else(|| p["input"].clone());
                let patch = args
                    .as_str()
                    .or_else(|| s(&args, "patch"))
                    .or_else(|| s(p, "input"))
                    .unwrap_or("");
                let paths = if name.ends_with("apply_patch") {
                    patch
                        .lines()
                        .filter_map(|line| {
                            [
                                "*** Add File: ",
                                "*** Update File: ",
                                "*** Delete File: ",
                                "*** Move to: ",
                            ]
                            .iter()
                            .find_map(|prefix| line.strip_prefix(prefix))
                        })
                        .map(String::from)
                        .collect()
                } else {
                    vec![]
                };
                return Ok(vec![Entry {
                    path: path_for(name, &args),
                    call_id: s(p,"call_id").map(String::from).or_else(||Some(base.id.clone())),
                    paths,
                    ..make("toolCall", "tool", None, Some(name.into()))
                }]);
            }
            "function_call_output" | "custom_tool_call_output" => {
                let output=text_blocks(&p["output"],&["text","input_text","output_text"]);
                let mut e=make("toolOutput","tool",Some(output.clone()),s(p,"name").map(String::from));
                e.call_id=s(p,"call_id").map(String::from);
                e.succeeded=p["is_error"].as_bool().map(|b|!b).or_else(||{
                    if output.trim_start().starts_with("Success."){Some(true)}else if output.trim_start().starts_with("Error"){Some(false)}else{
                        serde_json::from_str::<Value>(&output).ok().and_then(|v|v["success"].as_bool().or_else(||v["exit_code"].as_i64().map(|n|n==0)))
                    }
                });
                return Ok(vec![e]);
            }
            "reasoning" => {
                return Ok(vec![make(
                    "reasoning",
                    "assistant",
                    Some(text_blocks(&p["summary"], &["text", "summary_text"])),
                    None,
                )])
            }
            _ => return Ok(vec![]),
        }
    }
    let m = if agent == "codex" { p } else { &v["message"] };
    let role = s(m, "role").ok_or_else(|| failure("unsupported_shape"))?;
    let mut out = vec![];
    if role == "user" {
        if !foreign(v) && !foreign(m) {
            if let Some(t) = user_text(&m["content"]) {
                let kind = if agent == "codex"
                    && !s(p, "source")
                        .is_some_and(|s| ["user", "human", "input", "interactive"].contains(&s))
                {
                    "candidateUser"
                } else {
                    "message"
                };
                out.push(make(kind, "user", Some(t), None));
            }
        }
        if let Some(a) = m["content"].as_array() {
            for (i, b) in a
                .iter()
                .enumerate()
                .filter(|(_, b)| s(b, "type") == Some("tool_result"))
            {
                let mut e = make(
                    "toolOutput",
                    "tool",
                    Some(text_blocks(&b["content"], &["text"])),
                    None,
                );
                e.id = format!("{}.{}", base.id, i);
                e.call_id=s(b,"tool_use_id").map(String::from);
                e.succeeded=Some(!b["is_error"].as_bool().unwrap_or(false));
                out.push(e);
            }
        }
    } else if role == "assistant" {
        if let Some(model) = s(m, "model") {
            st.model = Some(model.into());
        }
        let t = text_blocks(&m["content"], &["text", "output_text"]);
        // Empty assistant messages still mean work started, so following prompts cannot merge backwards.
        let mut assistant = make("message", "assistant", Some(t), None);
        assistant.usage_key = s(m, "id").map(String::from);
        out.push(assistant);
        if let Some(blocks) = m["content"].as_array() {
            for (i, b) in blocks.iter().enumerate() {
                let mut e = match s(b, "type").unwrap_or("") {
                    "tool_use" | "toolCall" => {
                        let name = s(b, "name").ok_or_else(|| failure("unsupported_shape"))?;
                        let mut e = make("toolCall", "tool", None, Some(name.into()));
                        e.call_id=s(b,"id").map(String::from);
                        e.path = path_for(
                            name,
                            b.get("input")
                                .or_else(|| b.get("arguments"))
                                .unwrap_or(&Value::Null),
                        );
                        e
                    }
                    "thinking" => make(
                        "reasoning",
                        "assistant",
                        s(b, "thinking").map(String::from),
                        None,
                    ),
                    _ => continue,
                };
                e.id = format!("{}.{}", base.id, i);
                out.push(e);
            }
        }
        if m["usage"].is_object() {
            out.push(Entry {
                kind: "usage".into(),
                usage: Some(usage(&m["usage"], agent == "pi")),
                usage_key: s(m, "id")
                    .map(String::from)
                    .or_else(|| Some(base.id.clone())),
                ..base.clone()
            });
        }
        if let Some(reason) = s(m, "stop_reason").or_else(|| s(m, "stopReason")) {
            if ["end_turn", "stop", "stop_sequence", "error", "aborted"].contains(&reason) {
                out.push(Entry {
                    kind: "status".into(),
                    status: Some(
                        if ["error", "aborted"].contains(&reason) {
                            "interrupted"
                        } else {
                            "done"
                        }
                        .into(),
                    ),
                    ..base.clone()
                });
            }
        }
    } else if role == "toolResult" {
        let mut e=make("toolOutput","tool",Some(text_blocks(&m["content"], &["text"])),s(m,"toolName").map(String::from));
        e.call_id=s(m,"toolCallId").map(String::from);e.succeeded=Some(!m["isError"].as_bool().unwrap_or(false));out.push(e);
    }
    Ok(out)
}

/// Parse complete lines only. Checkpoint holds user text and statistics, never reply/tool/reasoning bodies.
/// Append resumes at the committed offset. Prefix mismatch/truncation replays safely under stable message IDs.
pub(super) fn load(
    path: &Path,
    c: &AgentConsent,
    previous: Option<Session>,
    persist: bool,
) -> Result<Session> {
    load_until(path,c,previous,persist,None)
}
pub(super) fn load_until(path:&Path,c:&AgentConsent,previous:Option<Session>,persist:bool,deadline:Option<std::time::Instant>)->Result<Session>{
    let mut file = fs::File::open(path).map_err(|_| failure("unreadable"))?;
    let size = file.metadata()?.len();
    if deadline.is_some() && size > 8 * 1024 * 1024 { return Err(failure("source_byte_budget")); }
    let mut st = previous.unwrap_or_default();
    // Replay old file checkpoints once to recover source paths and causal line order.
    if persist && st.checkpoint_format != super::CHECKPOINT_FORMAT { st = Session { reset_counts: true, ..Default::default() }; }
    st.checkpoint_format = super::CHECKPOINT_FORMAT.into();
    if st.offset > size
        || (!st.prefix_hash.is_empty() && prefix_digest(&mut file, st.offset)? != st.prefix_hash)
    {
        st = Session { reset_counts: true, ..Default::default() };
    }
    st.checkpoint_format = super::CHECKPOINT_FORMAT.into();
    file.seek(SeekFrom::Start(st.offset))?;
    let mut reader = BufReader::new(file);
    let mut head = vec![];
    let initial = st.offset == 0;
    loop {
        if deadline.is_some_and(|d|std::time::Instant::now()>=d){st.limited=true;break;}
        let mut line = Vec::new();
        let read = reader.by_ref().take(16*1024*1024+1).read_until(b'\n', &mut line)?;
        if read>16*1024*1024{return Err(failure("line_too_large"));}
        if read == 0 || !line.ends_with(b"\n") {
            break;
        }
        st.lines += 1;
        st.offset += read as u64;
        if line.iter().all(u8::is_ascii_whitespace) {
            continue;
        }
        let v: Value = serde_json::from_slice(&line).map_err(|_| failure("malformed_json"))?;
        if initial && head.len() < 40 {
            head.push(v.clone());
        }
        let mut entries = parse(&c.agent, &v, &mut st)?;
        // Metadata settles project/session exclusions before the next body line is opened.
        if !st.key.is_empty() && c.excluded(&st.key,st.project.as_deref()){st.entries.clear();return Ok(st);}
        for e in &mut entries {
            e.source_file = path.to_string_lossy().into_owned();
            e.source_line = st.lines;
            let order = e.ts.max(st.order_watermark.unwrap_or(i64::MIN));
            e.order_ms = Some(order);
            st.order_watermark = Some(order);
            if persist {
                if e.role != "user"
                    || !["message", "humanMessage", "candidateUser"].contains(&e.kind.as_str())
                {
                    e.text = None;
                } else {
                    if let Some(t) = &e.text {
                        e.original_chars = t.chars().count();
                        let t = redact(t);
                        let cap = c.prompt_max_chars.unwrap_or(usize::MAX);
                        e.truncated = t.chars().count() > cap;
                        e.text = Some(t.chars().take(cap).collect());
                    }
                }
            }
            let allowed = |p: &str| {
                let p = if Path::new(p).is_absolute() {
                    PathBuf::from(p)
                } else {
                    PathBuf::from(st.project.as_deref().unwrap_or("/")).join(p)
                };
                let p = crate::store::standardize(&p);
                !c.exclude
                    .projects
                    .iter()
                    .any(|x| below(&p.to_string_lossy(), &expand(x).to_string_lossy()))
            };
            if e.path.as_deref().is_some_and(|p| !allowed(p)) {
                e.path = None;
            }
            e.paths.retain(|p| allowed(p));
        }
        for mut e in entries {
            if persist && !c.content.user && e.role=="user" {e.text=None;}
            // Streaming usage snapshots replace their previous value; message occurrences keep their own IDs.
            if let Some(old) = st
                .entries
                .iter_mut()
                .find(|old| old.id == e.id && old.kind == e.kind)
            {
                *old = e;
            } else {
                st.entries.push(e);
            }
        }
    }
    if initial {
        recognize(&c.agent, &head)?;
    }
    if c.agent == "codex" {
        let has_signals = st.entries.iter().any(|e| e.kind == "humanMessage");
        if persist || has_signals {
            st.entries.retain(|e| e.kind != "candidateUser");
        }
        for e in &mut st.entries {
            if e.kind == "humanMessage" {
                e.kind = "message".into();
            }
        }
    }
    if st.offset > 0 && st.key.is_empty() {
        return Err(failure("missing_session_identity"));
    }
    let mut file = reader.into_inner();
    if deadline.is_none(){st.prefix_hash = prefix_digest(&mut file, st.offset)?;}
    Ok(st)
}

/// Header inspection only, bounded to the same 256 KiB / 40 complete lines as the original adapter.
pub(super) fn detect(path: &Path, c: &AgentConsent) -> Result<()> {
    c.require_read()?;
    let file = fs::File::open(path).map_err(|_| failure("unreadable"))?;
    let mut reader = BufReader::new(file.take(256 * 1024));
    let mut head = vec![];
    for _ in 0..40 {
        let mut line = vec![];
        if reader.read_until(b'\n', &mut line)? == 0 || !line.ends_with(b"\n") {
            break;
        }
        if line.iter().all(u8::is_ascii_whitespace) {
            continue;
        }
        head.push(serde_json::from_slice(&line).map_err(|_| failure("malformed_json"))?);
    }
    recognize(&c.agent, &head)
}

fn prefix_digest(file: &mut fs::File, len: u64) -> Result<String> {
    use sha2::{Digest, Sha256};
    file.seek(SeekFrom::Start(0))?;
    let mut reader = file.take(len);
    let mut digest = Sha256::new();
    let mut buffer = [0u8; 64 * 1024];
    loop {
        let n = reader.read(&mut buffer)?;
        if n == 0 {
            break;
        }
        digest.update(&buffer[..n]);
    }
    Ok(format!("{:x}", digest.finalize()))
}
